"""Load Aave V3 Sepolia contracts and reserve relationships into Neo4j.

The source is Aave DAO's autogenerated address book. It is preferable to a
hand-maintained address list because each sync records the current official
contract and reserve-token mappings.
"""

import json
import re
from datetime import datetime, timezone

from db.connection import get_session
from db.graph_builder import ensure_schema
from db.loaders.common import fetch_text, normalize_address


CHAIN_ID = 11155111
CHAIN_NAME = "Ethereum Sepolia"
PROTOCOL_KEY = "aave-v3-sepolia"
SOURCE_URL = (
    "https://raw.githubusercontent.com/aave-dao/aave-address-book/"
    "refs/heads/main/src/AaveV3Sepolia.sol"
)

CORE_ROLES = {
    "POOL_ADDRESSES_PROVIDER": "addresses_provider",
    "POOL": "pool",
    "POOL_CONFIGURATOR": "pool_configurator",
    "ORACLE": "oracle",
    "ACL_MANAGER": "acl_manager",
    "AAVE_PROTOCOL_DATA_PROVIDER": "protocol_data_provider",
    "UI_POOL_DATA_PROVIDER": "ui_pool_data_provider",
    "WETH_GATEWAY": "weth_gateway",
}

ASSET_PATTERN = re.compile(
    r"address\s+internal\s+constant\s+([A-Za-z0-9_]+?)_"
    r"(INTEREST_RATE_STRATEGY|STATIC_A_TOKEN|UNDERLYING|A_TOKEN|V_TOKEN|S_TOKEN|ORACLE)\s*=\s*"
    r"(0x[a-fA-F0-9]{40})\s*;",
    re.MULTILINE,
)
DECIMALS_PATTERN = re.compile(
    r"uint8\s+internal\s+constant\s+([A-Za-z0-9_]+)_DECIMALS\s*=\s*(\d+)\s*;"
)
CORE_ADDRESS_PATTERN = re.compile(
    r"(?:address|I[A-Za-z0-9_]*)\s+internal\s+constant\s+"
    r"([A-Z][A-Z0-9_]*)\s*=\s*"
    r"(?:[A-Za-z0-9_]+\s*\(\s*)?"
    r"(0x[a-fA-F0-9]{40})\s*\)?\s*;",
    re.MULTILINE,
)


def _parse_address_book(source: str):
    match = re.search(r"library\s+AaveV3[A-Za-z0-9]+Assets\s*\{", source)
    if not match:
        raise ValueError("Aave V3 assets library was not found in address book")
    core_source = source[:match.start()]
    assets_source = source[match.end():]
    core = [
        {
            "name": constant,
            "role": CORE_ROLES.get(constant, constant.lower()),
            "address": normalize_address(address),
        }
        for constant, address in CORE_ADDRESS_PATTERN.findall(core_source)
    ]

    decimals = {symbol: int(value) for symbol, value in DECIMALS_PATTERN.findall(assets_source)}
    assets = {}
    for symbol, kind, address in ASSET_PATTERN.findall(assets_source):
        asset = assets.setdefault(symbol, {"symbol": symbol})
        asset[kind.lower()] = normalize_address(address)
    for symbol, asset in assets.items():
        asset["decimals"] = decimals.get(symbol)
        if "underlying" not in asset:
            raise ValueError(f"Aave address book has no underlying address for {symbol}")
    return core, list(assets.values())


def _load_core(session, contracts, synced_at):
    session.run(
        """
        MERGE (chain:Chain {chain_id:$chain_id})
        SET chain.name=$chain_name, chain.testnet=true
        MERGE (protocol:Protocol {key:$key})
        SET protocol.name='Aave V3', protocol.version='3', protocol.verified=true,
            protocol.chain_id=$chain_id, protocol.source_url=$source,
            protocol.last_synced_at=$synced_at
        MERGE (protocol)-[:DEPLOYED_ON]->(chain)
        WITH protocol
        UNWIND $contracts AS item
        MERGE (contract:Contract {chain_id:$chain_id, address:item.address})
        SET contract.name=item.name, contract.role=item.role, contract.verified=true,
            contract.source='aave-address-book', contract.last_synced_at=$synced_at
        MERGE (protocol)-[rel:DEPLOYED_CONTRACT]->(contract)
        SET rel.role=item.role
        """,
        chain_id=CHAIN_ID,
        chain_name=CHAIN_NAME,
        key=PROTOCOL_KEY,
        source=SOURCE_URL,
        synced_at=synced_at,
        contracts=contracts,
    ).consume()
    session.run(
        """
        MATCH (c:Contract {chain_id:$chain_id, role:'pool'})
        SET c:Pool, c.protocol='Aave V3', c.action='supply'
        """,
        chain_id=CHAIN_ID,
    ).consume()


def _load_asset(session, asset, synced_at):
    session.run(
        """
        MATCH (protocol:Protocol {key:$key})
        MATCH (pool:Contract {chain_id:$chain_id, role:'pool'})
        MERGE (token:Token {chain_id:$chain_id, address:$underlying})
        SET token.symbol=$symbol, token.decimals=$decimals, token.verified=true,
            token.source='aave-address-book', token.last_synced_at=$synced_at
        MERGE (protocol)-[:SUPPORTS_ASSET]->(token)
        MERGE (pool)-[:SUPPORTS_TOKEN]->(token)
        MERGE (pool)-[:CAN_SUPPLY]->(token)
        MERGE (pool)-[:CAN_WITHDRAW]->(token)
        """,
        key=PROTOCOL_KEY,
        chain_id=CHAIN_ID,
        synced_at=synced_at,
        **asset,
    ).consume()

    contract_kinds = (
        ("a_token", "aToken", "REPRESENTS"),
        ("v_token", "variableDebtToken", "DEBT_FOR"),
        ("oracle", "oracle", "PRICES"),
        ("static_a_token", "staticAToken", "REPRESENTS"),
    )
    for field, kind, relation in contract_kinds:
        address = asset.get(field)
        if not address:
            continue
        session.run(
            f"""
            MATCH (protocol:Protocol {{key:$key}})-[:SUPPORTS_ASSET]->(token:Token {{chain_id:$chain_id, address:$underlying}})
            MERGE (contract:Contract {{chain_id:$chain_id, address:$address}})
            SET contract.name=$symbol + ' ' + $kind, contract.role=$kind,
                contract.verified=true, contract.source='aave-address-book',
                contract.last_synced_at=$synced_at
            MERGE (protocol)-[:DEPLOYED_CONTRACT {{role:$kind}}]->(contract)
            MERGE (contract)-[:{relation}]->(token)
            """,
            key=PROTOCOL_KEY,
            chain_id=CHAIN_ID,
            underlying=asset["underlying"],
            address=address,
            symbol=asset["symbol"],
            kind=kind,
            synced_at=synced_at,
        ).consume()

    if asset.get("v_token"):
        session.run(
            """
            MATCH (pool:Contract {chain_id:$chain_id, role:'pool'})
            MATCH (token:Token {chain_id:$chain_id, address:$underlying})
            MERGE (pool)-[:CAN_BORROW]->(token)
            MERGE (pool)-[:CAN_REPAY]->(token)
            """,
            chain_id=CHAIN_ID,
            underlying=asset["underlying"],
        ).consume()


def load_aave_v3(ensure_constraints=True):
    if ensure_constraints:
        ensure_schema()
    source = fetch_text(SOURCE_URL)
    contracts, assets = _parse_address_book(source)
    if not any(item["role"] == "pool" for item in contracts):
        raise ValueError("Aave Pool address was not found in the official address book")

    synced_at = datetime.now(timezone.utc).isoformat()
    with get_session() as session:
        _load_core(session, contracts, synced_at)
        for asset in assets:
            _load_asset(session, asset, synced_at)
        for action in ("supply", "withdraw", "borrow", "repay"):
            session.run(
                """
                MATCH (protocol:Protocol {key:$key})
                MERGE (action:Action {name:$action})
                MERGE (protocol)-[:SUPPORTS_ACTION]->(action)
                """,
                key=PROTOCOL_KEY,
                action=action,
            ).consume()
    return {
        "source": SOURCE_URL,
        "contracts": len(contracts),
        "assets": len(assets),
        "symbols": sorted(asset["symbol"] for asset in assets),
    }


if __name__ == "__main__":
    print(json.dumps(load_aave_v3(), indent=2))
